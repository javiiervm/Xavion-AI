
from __future__ import annotations

import json
import re
import sys
import time
from pathlib import Path
from typing import Any

from xavion.core.config import resolve_model_name
from xavion.core.engine import XavionAI
from xavion.version import DISPLAY_NAME, NAME, VERSION


# Xavion session files are created with this name by XavionAI.
_SESSION_ID_PATTERN = re.compile(r"chat_\d{8}_\d{6}\Z")


def emit(event_type: str, **payload: Any) -> None:
    """Write one newline-delimited JSON event for Quickshell."""
    print(
        json.dumps(
            {
                "type": event_type,
                **payload,
            },
            ensure_ascii=False,
        ),
        flush=True,
    )


def valid_session_id(session_id: str) -> bool:
    """Accept only the session IDs generated by Xavion's engine."""
    return _SESSION_ID_PATTERN.fullmatch(session_id) is not None


def get_capabilities(ai: XavionAI, refresh: bool = False) -> dict[str, Any]:
    """Return the active model capabilities."""
    return ai.get_model_capabilities(refresh=refresh).to_dict()


def supports_reasoning(ai: XavionAI) -> bool:
    """Check reasoning support using the engine when available."""
    checker = getattr(ai, "supports_reasoning", None)

    if callable(checker):
        return bool(checker())

    return bool(get_capabilities(ai).get("thinking", False))


def reasoning_mode(ai: XavionAI) -> str:
    """Return the currently configured reasoning mode."""
    return str(getattr(ai, "reasoning_mode", "off"))


def model_state(ai: XavionAI) -> dict[str, Any]:
    """Build model metadata shared by frontend events."""
    return {
        "reasoning_supported": supports_reasoning(ai),
        "reasoning_mode": reasoning_mode(ai),
        "capabilities": get_capabilities(ai),
    }


def handle_command(ai: XavionAI, command: dict[str, Any]) -> None:
    command_type = command.get("type")

    # ============================================================
    # CHAT
    # ============================================================

    if command_type == "chat":
        message = command.get("message", "")
        images = command.get("images", [])

        if not isinstance(message, str):
            emit("error", message="Message must be a string.")
            return

        if not isinstance(images, list):
            emit("error", message="Images must be a list.")
            return

        message = message.strip()

        if not message and not images:
            emit(
                "error",
                message="Message cannot be empty without an image.",
            )
            return

        intent_mode = str(command.get("intent_mode", "auto"))
        tone_mode = str(command.get("tone_mode", "adaptive"))

        # Stream the core's typed events. The bridge is the only Quickshell-
        # specific adapter: reasoning logic stays in XavionAI.
        try:
            for event in ai.chat_events(
                message,
                intent_mode=intent_mode,
                tone_mode=tone_mode,
                images=images,
            ):
                event_type = event.get("type")

                if event_type == "start":
                    # Keep the legacy 'thinking' field for older consumers,
                    # but only signal real thinking via reasoning_start below.
                    emit(
                        "start",
                        thinking=False,
                        reasoning_mode=event.get("reasoning_mode", "off"),
                        reasoning_enabled=bool(event.get("reasoning_enabled", False)),
                        reasoning_reason=str(event.get("reasoning_reason", "")),
                    )
                elif event_type in {
                    "reasoning_start",
                    "reasoning_end",
                    "response_start",
                }:
                    emit(event_type)
                elif event_type == "reasoning_chunk":
                    # Never include reasoning text in the final assistant bubble.
                    if event.get("text"):
                        emit("reasoning_chunk", text=event["text"])
                elif event_type == "response_chunk":
                    # Keep the established 'chunk' contract for both Xavion
                    # views (embedded launcher and legacy panel).
                    if event.get("text"):
                        emit("chunk", text=event["text"])
                elif event_type == "done":
                    # Metadata only: never forward raw base64 attachments.
                    emit(
                        "done",
                        images=event.get("images", []),
                        reasoning_enabled=bool(event.get("reasoning_enabled", False)),
                        reasoning_used=bool(event.get("reasoning_used", False)),
                    )

        except Exception as exc:
            emit("error", message=str(exc))

        return

    # ============================================================
    # CONVERSATION MANAGEMENT
    # ============================================================

    if command_type == "new":
        session_id = ai.start_new_session()
        emit("new_done", session_id=session_id)
        return

    if command_type == "list_sessions":
        emit(
            "sessions",
            sessions=ai.list_sessions_detailed(),
        )
        return

    if command_type == "load_session":
        session_id = str(command.get("session_id", "")).strip()

        if not valid_session_id(session_id):
            emit("error", message="Invalid session ID.")
            return

        if not ai.load_session(session_id):
            emit("error", message="Conversation not found.")
            return

        messages = []

        for turn in ai.history:
            if turn.get("user"):
                user_message = {
                    "role": "user",
                    "text": str(turn["user"]),
                }

                if turn.get("images"):
                    user_message["images"] = turn["images"]

                messages.append(user_message)

            if turn.get("assistant"):
                messages.append({
                    "role": "assistant",
                    "text": str(turn["assistant"]),
                })

        emit(
            "session_loaded",
            session_id=session_id,
            messages=messages,
            model=ai.model_name,
            **model_state(ai),
        )
        return

    if command_type == "delete_sessions":
        requested_ids = command.get("session_ids", [])

        if not isinstance(requested_ids, list) or not requested_ids:
            emit(
                "error",
                message="No conversations selected for deletion.",
            )
            return

        # Validate the complete batch before modifying any files.
        if any(
            not isinstance(session_id, str)
            or not valid_session_id(session_id)
            for session_id in requested_ids
        ):
            emit(
                "error",
                message="Invalid conversation selection.",
            )
            return

        session_ids = list(dict.fromkeys(requested_ids))
        data_dir = Path("data")

        deleted = []
        failed = []

        for session_id in session_ids:
            filepath = data_dir / f"{session_id}.json"

            try:
                if filepath.is_symlink() or not filepath.is_file():
                    failed.append(session_id)
                    continue

                filepath.unlink()
                deleted.append(session_id)

            except OSError:
                failed.append(session_id)

        # Clear the in-memory context when the active chat is deleted.
        active_reset = ai.current_session_id in deleted

        if active_reset:
            ai.start_new_session()

        # Prevent a new session from reusing an ID deleted
        # within the same second.
        if ai.current_session_id in deleted:
            seconds_ahead = 1

            while True:
                candidate = time.strftime(
                    "chat_%Y%m%d_%H%M%S",
                    time.localtime(time.time() + seconds_ahead),
                )

                if candidate not in deleted and not (
                    data_dir / f"{candidate}.json"
                ).exists():
                    ai.current_session_id = candidate
                    break

                seconds_ahead += 1

        emit(
            "sessions_deleted",
            deleted=deleted,
            failed=failed,
            active_reset=active_reset,
            sessions=ai.list_sessions_detailed(),
        )
        return

    if command_type == "reset":
        ai.reset_history()
        emit("reset_done")
        return

    # ============================================================
    # MODEL MANAGEMENT
    # ============================================================

    if command_type == "list_models":
        emit(
            "models",
            models=ai.list_available_models(),
            active_model=ai.model_name,
            **model_state(ai),
        )
        return

    if command_type == "set_model":
        requested = str(command.get("model", "")).strip()

        if not requested:
            emit(
                "error",
                message="Model name cannot be empty.",
            )
            return

        models = ai.list_available_models()

        if requested not in models:
            emit(
                "error",
                message=f"Model '{requested}' is not installed.",
            )
            emit(
                "models",
                models=models,
                active_model=ai.model_name,
                **model_state(ai),
            )
            return

        ai.model_name = requested

        emit(
            "model_changed",
            model=ai.model_name,
            models=models,
            **model_state(ai),
        )
        return

    if command_type == "get_capabilities":
        emit(
            "capabilities",
            capabilities=get_capabilities(ai, refresh=True),
        )
        return

    # ============================================================
    # REASONING MANAGEMENT
    # ============================================================

    if command_type == "set_reasoning":
        mode = str(command.get("mode", "")).strip().lower()

        if mode not in {"auto", "on", "off"}:
            emit(
                "error",
                message="Reasoning mode must be 'auto', 'on', or 'off'.",
            )
            return

        # The preference is shared between frontends and can be retained even
        # when the currently selected model has no reasoning capability.

        if not hasattr(ai, "reasoning_mode"):
            emit(
                "error",
                message=(
                    "Reasoning configuration is not available "
                    "in the current Xavion engine."
                ),
            )
            return

        ai.reasoning_mode = mode

        emit(
            "reasoning_changed",
            mode=ai.reasoning_mode,
            supported=supports_reasoning(ai),
        )
        return

    # ============================================================
    # HEALTH CHECK
    # ============================================================

    if command_type == "ping":
        emit("pong")
        return

    emit(
        "error",
        message=f"Unknown command type: {command_type}",
    )


def main() -> None:
    model_name = resolve_model_name()

    if model_name is None:
        emit(
            "error",
            message=(
                "No default model is configured. "
                "Run 'python main.py --config'."
            ),
        )
        return

    ai = XavionAI(model_name=model_name)
    ai.start_new_session()

    models = ai.list_available_models()

    emit(
        "ready",
        name=NAME,
        display_name=DISPLAY_NAME,
        version=VERSION,
        model=ai.model_name,
        models=models,
        **model_state(ai),
    )

    for raw_line in sys.stdin:
        raw_line = raw_line.strip()

        if not raw_line:
            continue

        try:
            command = json.loads(raw_line)

        except json.JSONDecodeError as exc:
            emit(
                "error",
                message=f"Invalid JSON command: {exc}",
            )
            continue

        if not isinstance(command, dict):
            emit(
                "error",
                message="Command must be a JSON object.",
            )
            continue

        try:
            handle_command(ai, command)

        except Exception as exc:
            emit("error", message=str(exc))


if __name__ == "__main__":
    main()
